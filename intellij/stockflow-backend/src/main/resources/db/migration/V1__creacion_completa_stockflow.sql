-- 15. alerta_stock
CREATE TABLE alerta_stock (
    alerta_id           BIGINT GENERATED BY DEFAULT AS IDENTITY,
    producto_id         BIGINT        NOT NULL,
    ubicacion_id        BIGINT        NOT NULL,
    cantidad_detectada  NUMERIC(14,3) NOT NULL,
    stock_minimo        NUMERIC(14,3) NOT NULL,
    estado              VARCHAR(20)   NOT NULL DEFAULT 'ABIERTA',
    generada_at         TIMESTAMPTZ   NOT NULL DEFAULT now(),
    resuelta_at         TIMESTAMPTZ   NULL,
    CONSTRAINT pk_alerta_stock PRIMARY KEY (alerta_id),
    CONSTRAINT fk_alerta_producto  FOREIGN KEY (producto_id)  REFERENCES producto (producto_id),
    CONSTRAINT fk_alerta_ubicacion FOREIGN KEY (ubicacion_id) REFERENCES ubicacion (ubicacion_id),
    CONSTRAINT ck_alerta_estado CHECK (estado IN ('ABIERTA','RESUELTA')),
    CONSTRAINT ck_alerta_resuelta CHECK (estado <> 'RESUELTA' OR resuelta_at IS NOT NULL),
    CONSTRAINT ck_alerta_cantidades CHECK (cantidad_detectada >= 0 AND stock_minimo >= 0)
);

-- 16. historial_estado_solicitud · RN-05 (traza de transiciones)
CREATE TABLE historial_estado_solicitud (
    historial_id     BIGINT GENERATED BY DEFAULT AS IDENTITY,
    solicitud_id     BIGINT      NOT NULL,
    estado_anterior  VARCHAR(20) NULL,
    estado_nuevo     VARCHAR(20) NOT NULL,
    motivo           VARCHAR(200) NULL,
    cambiado_por     BIGINT      NOT NULL,
    cambiado_at      TIMESTAMPTZ NOT NULL DEFAULT now(),
    CONSTRAINT pk_historial_estado_solicitud PRIMARY KEY (historial_id),
    CONSTRAINT fk_historial_solicitud FOREIGN KEY (solicitud_id) REFERENCES solicitud (solicitud_id),
    CONSTRAINT fk_historial_usuario   FOREIGN KEY (cambiado_por) REFERENCES usuario (usuario_id),
    CONSTRAINT ck_historial_estado_nuevo CHECK (estado_nuevo IN
        ('BORRADOR','ENVIADA','APROBADA','RECHAZADA','ATENDIDA','CANCELADA')),
    CONSTRAINT ck_historial_estado_anterior CHECK (estado_anterior IS NULL OR estado_anterior IN
        ('BORRADOR','ENVIADA','APROBADA','RECHAZADA','ATENDIDA','CANCELADA'))
);

