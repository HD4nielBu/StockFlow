-- ---------------------------------------------------------------------
-- RN-01 / RN-10 operativo: el movimiento y la auditoría no se borran
-- ---------------------------------------------------------------------
CREATE OR REPLACE FUNCTION fn_impedir_borrado_historico()
RETURNS trigger
LANGUAGE plpgsql
AS $$
BEGIN
    RAISE EXCEPTION 'Los registros de % no se pueden eliminar (trazabilidad)', TG_TABLE_NAME;
END;
$$;

CREATE TRIGGER trg_movimiento_no_delete
    BEFORE DELETE ON movimiento_inventario
    FOR EACH ROW EXECUTE FUNCTION fn_impedir_borrado_historico();

CREATE TRIGGER trg_auditoria_no_delete
    BEFORE DELETE ON auditoria
    FOR EACH ROW EXECUTE FUNCTION fn_impedir_borrado_historico();

CREATE TRIGGER trg_historial_solicitud_no_delete
    BEFORE DELETE ON historial_estado_solicitud
    FOR EACH ROW EXECUTE FUNCTION fn_impedir_borrado_historico();

-- ---------------------------------------------------------------------
-- RF-19 · Kardex: vista derivada de los movimientos (no se guarda dos veces)
-- ---------------------------------------------------------------------
CREATE VIEW vw_kardex AS
SELECT m.movimiento_id,
       m.ocurrido_at,
       p.codigo        AS codigo_producto,
       p.nombre        AS producto,
       ub.codigo       AS ubicacion,
       m.tipo,
       CASE WHEN m.tipo IN ('ENTRADA','AJUSTE_POSITIVO','TRANSFERENCIA_ENTRADA')
            THEN m.cantidad ELSE 0 END AS entrada,
       CASE WHEN m.tipo IN ('SALIDA','AJUSTE_NEGATIVO','TRANSFERENCIA_SALIDA')
            THEN m.cantidad ELSE 0 END AS salida,
       m.saldo_resultante,
       m.referencia_tipo,
       us.username     AS registrado_por,
       m.motivo
FROM movimiento_inventario m
JOIN producto p   ON p.producto_id = m.producto_id
JOIN ubicacion ub ON ub.ubicacion_id = m.ubicacion_id
JOIN usuario us   ON us.usuario_id = m.usuario_id;

